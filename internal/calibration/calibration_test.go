func TestAutoCalibrateWithProfile(t *testing.T) {
	t.Parallel()

	t.Run("Load existing profile", func(t *testing.T) {
		t.Parallel()
		tmpDir := t.TempDir()
		profilePath := tmpDir + "/profile.json"

		// Create a valid profile
		profile := NewProfile()
		profile.OptimalParallelThreshold = 4096
		profile.OptimalFFTThreshold = 1000000
		profile.OptimalStrassenThreshold = 256
		if err := profile.SaveProfile(profilePath); err != nil {
			t.Fatalf("Failed to save profile: %v", err)
		}

		registry := map[string]fibonacci.Calculator{
			"fast": &MockCalculator{name: "fast"},
		}

		cfg := config.AppConfig{
			Timeout: 1 * time.Second,
		}

		var outBuf bytes.Buffer
		ctx := context.Background()
		updated, ok := AutoCalibrateWithProfile(ctx, cfg, &outBuf, registry, profilePath)

		if !ok {
			t.Error("AutoCalibrateWithProfile should succeed with existing profile")
		}
		if updated.Threshold != 4096 {
			t.Errorf("Threshold = %d, want 4096", updated.Threshold)
		}
		output := outBuf.String()
		if !strings.Contains(output, "Using cached calibration") {
			t.Errorf("Output should mention cached calibration. Got: %s", output)
		}
	})

	// SEC-01: the runtime auto-calibrate path must not trust a hardware-valid
	// but forged on-disk profile whose thresholds are out of range. IsValid()
	// checks hardware compatibility only, so a negative threshold would leak
	// straight into the running config via applyCachedProfile.
	t.Run("Forged fresh profile with negative threshold is not applied", func(t *testing.T) {
		t.Parallel()
		tmpDir := t.TempDir()
		profilePath := tmpDir + "/forged.json"

		// NewProfile() stamps the current hardware fields, so IsValid() passes;
		// CalibratedAt is now, so it is fresh (not stale). Only the threshold
		// is forged.
		// -2, not -1: -1 is config.ThresholdDisabled, a value this package's own
		// candidate generators produce and which is valid since audit H-02.
		// Only something below it is genuinely out of range.
		profile := NewProfile()
		profile.OptimalParallelThreshold = -2
		profile.OptimalFFTThreshold = 600000
		profile.OptimalStrassenThreshold = 4096
		if err := profile.SaveProfile(profilePath); err != nil {
			t.Fatalf("Failed to save forged profile: %v", err)
		}

		registry := map[string]fibonacci.Calculator{
			"fast": &MockCalculator{name: "fast"},
		}
		cfg := config.AppConfig{Timeout: 5 * time.Second}

		var outBuf bytes.Buffer
		ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		defer cancel()
		updated, _ := AutoCalibrateWithProfile(ctx, cfg, &outBuf, registry, profilePath)

		if updated.Threshold < config.ThresholdDisabled {
			t.Fatalf("forged out-of-range threshold leaked via auto-calibrate: Threshold=%d", updated.Threshold)
		}
		if strings.Contains(outBuf.String(), "Using cached calibration") {
			t.Errorf("forged profile must not be applied as a cached calibration; output=%q", outBuf.String())
		}
	})

	// H-02: the mirror image of the test above. ThresholdDisabled is not a
	// forged value, it is what the candidate generators in adaptive.go produce
	// as their sequential / no-FFT baseline (FIB-02). Rejecting it threw away
	// the calibration's own result on hosts where that baseline wins, and
	// re-ran a fast pass that overwrote it with a plain default.
	t.Run("Fresh profile with disabled thresholds is applied", func(t *testing.T) {
		t.Parallel()
		tmpDir := t.TempDir()
		profilePath := tmpDir + "/sequential.json"

		profile := NewProfile()
		profile.OptimalParallelThreshold = config.ThresholdDisabled
		profile.OptimalFFTThreshold = config.ThresholdDisabled
		profile.OptimalStrassenThreshold = 3072
		if err := profile.SaveProfile(profilePath); err != nil {
			t.Fatalf("Failed to save profile: %v", err)
		}

		registry := map[string]fibonacci.Calculator{
			"fast": &MockCalculator{name: "fast"},
		}
		cfg := config.AppConfig{Timeout: 5 * time.Second}

		var outBuf bytes.Buffer
		ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		defer cancel()
		updated, ok := AutoCalibrateWithProfile(ctx, cfg, &outBuf, registry, profilePath)

		if !ok {
			t.Fatal("a hardware-valid, fresh profile must be applied")
		}
		if updated.Threshold != config.ThresholdDisabled {
			t.Errorf("Threshold = %d, want %d (disabled)", updated.Threshold, config.ThresholdDisabled)
		}
		if updated.FFTThreshold != config.ThresholdDisabled {
			t.Errorf("FFTThreshold = %d, want %d (disabled)", updated.FFTThreshold, config.ThresholdDisabled)
		}
		if !strings.Contains(outBuf.String(), "Using cached calibration") {
			t.Errorf("expected the cached profile to be reported as used; output=%q", outBuf.String())
		}
	})

	// The persisted form must survive a round trip through config.Validate,
	// which is what app.New applies to a loaded profile. Before H-02 this is
	// exactly where the sequential result was dropped.
	t.Run("Disabled thresholds survive persist and validate", func(t *testing.T) {
		t.Parallel()
		tmpDir := t.TempDir()
		profilePath := tmpDir + "/roundtrip.json"

		saved := NewProfile()
		saved.OptimalParallelThreshold = config.ThresholdDisabled
		saved.OptimalFFTThreshold = config.ThresholdDisabled
		saved.OptimalStrassenThreshold = 3072
		if err := saved.SaveProfile(profilePath); err != nil {
			t.Fatalf("Failed to save profile: %v", err)
		}

		cfg := config.AppConfig{Timeout: time.Minute, Algo: "fast", N: 100}
		loaded, ok := LoadCachedCalibration(cfg, profilePath)
		if !ok {
			t.Fatal("LoadCachedCalibration must accept a hardware-valid profile")
		}
		if err := loaded.Validate([]string{"fast"}); err != nil {
			t.Fatalf("a persisted sequential profile must pass Validate, got: %v", err)
		}
	})

	t.Run("Quick calibration fallback", func(t *testing.T) {
		t.Parallel()
		tmpDir := t.TempDir()
		profilePath := tmpDir + "/profile.json"

		registry := map[string]fibonacci.Calculator{
			"fast": &MockCalculator{name: "fast"},
		}

		cfg := config.AppConfig{
			Timeout: 5 * time.Second,
		}

		var outBuf bytes.Buffer
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
		defer cancel()

		updated, ok := AutoCalibrateWithProfile(ctx, cfg, &outBuf, registry, profilePath)

		// Quick calibration may succeed or timeout; both paths must assert
		// something (TEST-02: no silent-green branch).
		if ok {
			if updated.Threshold == 0 {
				t.Error("Threshold should be set after quick calibration")
			}
			if output := outBuf.String(); !strings.Contains(output, "calibration") {
				t.Errorf("Output should mention calibration. Got: %s", output)
			}
		} else {
			if updated != cfg {
				t.Errorf("config must be returned unchanged on failure, got %+v", updated)
			}
			if !strings.Contains(outBuf.String(), "auto-calibration failed") {
				t.Errorf("failure path must warn the user (ERR-05), got: %q", outBuf.String())
			}
		}
	})

	t.Run("Full calibration fallback", func(t *testing.T) {
		t.Parallel()
		tmpDir := t.TempDir()
		profilePath := tmpDir + "/profile.json"

		registry := map[string]fibonacci.Calculator{
			"fast":   &MockCalculator{name: "fast"},
			"matrix": &MockCalculator{name: "matrix"},
		}

		cfg := config.AppConfig{
			Timeout: 5 * time.Second,
		}

		var outBuf bytes.Buffer
		ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		defer cancel()

		updated, ok := AutoCalibrateWithProfile(ctx, cfg, &outBuf, registry, profilePath)

		// Full calibration may succeed or timeout; both paths must assert
		// something (TEST-02: no silent-green branch).
		if ok {
			if updated.Threshold == 0 {
				t.Error("Threshold should be set after full calibration")
			}
		} else {
			if updated != cfg {
				t.Errorf("config must be returned unchanged on failure, got %+v", updated)
			}
			if !strings.Contains(outBuf.String(), "auto-calibration failed") {
				t.Errorf("failure path must warn the user (ERR-05), got: %q", outBuf.String())
			}
		}
	})

	t.Run("Failed auto-calibration warns the user", func(t *testing.T) {
		t.Parallel()
		registry := map[string]fibonacci.Calculator{
			"fast": &MockCalculator{name: "fast"},
		}
		ctx, cancel := context.WithCancel(context.Background())
		cancel() // every strategy fails on the dead context

		var outBuf bytes.Buffer
		updated, ok := AutoCalibrateWithProfile(ctx, config.AppConfig{Threshold: 1234}, &outBuf, registry, filepath.Join(t.TempDir(), "p.json"))

		if ok {
			t.Fatal("expected auto-calibration to fail on a canceled context")
		}
		if updated.Threshold != 1234 {
			t.Errorf("config must be returned unchanged on failure, got Threshold=%d", updated.Threshold)
		}
		// ERR-05: the user explicitly asked for --auto-calibrate; a silent
		// fallback to defaults leaves them believing calibration happened.
		if !strings.Contains(outBuf.String(), "auto-calibration failed") {
			t.Errorf("failure must warn the user; output=%q", outBuf.String())
		}
	})

	t.Run("No fast calculator", func(t *testing.T) {
		t.Parallel()
		tmpDir := t.TempDir()
		profilePath := tmpDir + "/profile.json"

		registry := map[string]fibonacci.Calculator{} // Empty

		cfg := config.AppConfig{
			Timeout:   1 * time.Second,
			Threshold: 0, // Explicitly set to 0
		}

		var outBuf bytes.Buffer
		ctx, cancel := context.WithTimeout(context.Background(), 100*time.Millisecond)
		defer cancel()

		updated, ok := AutoCalibrateWithProfile(ctx, cfg, &outBuf, registry, profilePath)

		// QuickCalibrate might succeed even without fast calculator (it uses bigfft directly)
		// So we check that if it fails, the config remains unchanged
		if !ok {
			if updated.Threshold != cfg.Threshold {
				t.Errorf("Config should remain unchanged on failure. Threshold = %d, want %d",
					updated.Threshold, cfg.Threshold)
			}
		} else {
			// If it succeeded (via QuickCalibrate), thresholds should be set
			if updated.Threshold == 0 {
				t.Error("If calibration succeeded, threshold should be set")
			}
		}
	})
}

